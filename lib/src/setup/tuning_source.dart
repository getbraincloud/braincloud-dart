// The project's tuning value as generated Dart source: written once per project, compiled into
// the app, and needed to read bc_config.json's values.
import 'dart:io';
import 'dart:math';
import 'dart:typed_data';

import '../config/client_tuning.dart' show tuningLength;

const tuningFileName = 'braincloud_tuning.dart';

final _random = Random.secure();

Uint8List _bytes(int n) => Uint8List.fromList(List.generate(n, (_) => _random.nextInt(256)));

Uint8List newTuning() => _bytes(tuningLength);

String _array(String name, List<int> bytes) {
  final hex = [for (final b in bytes) '0x${b.toRadixString(16).padLeft(2, '0')}'];
  final lines = [for (var i = 0; i < hex.length; i += 12) '  ${hex.sublist(i, min(i + 12, hex.length)).join(', ')},'];
  return 'const $name = <int>[\n${lines.join('\n')}\n];';
}

/// value[i] = t0[t3[i]] ^ t1[i] ^ t2[(i * k) & 31], every part random per write.
String tuningSource(List<int> value) {
  final t3 = List.generate(tuningLength, (i) => i)..shuffle(_random);
  final k = _random.nextInt(16) * 2 + 1;
  final t1 = _bytes(tuningLength);
  final t2 = _bytes(tuningLength);
  final t0 = Uint8List(tuningLength);
  for (var i = 0; i < tuningLength; i++) {
    t0[t3[i]] = value[i] ^ t1[i] ^ t2[(i * k) & 31];
  }
  final out = [
    "// Generated by brainCloud setup. Regenerate, don't edit; keep it out of public source control.",
    '// ignore_for_file: type=lint',
    "import 'package:braincloud/braincloud.dart';",
    '',
    _array('_t0', t0),
    _array('_t1', t1),
    _array('_t2', t2),
    _array('_t3', t3),
    '',
    'List<int> _fill() => [for (var i = 0; i < 32; i++) _t0[_t3[i]] ^ _t1[i] ^ _t2[(i * $k) & 31]];',
    '',
    '/// Call once before BrainCloudWrapper.init().',
    'void braincloudBootstrap() => BrainCloudWrapper.bootstrap(_fill);',
    '',
  ].join('\n');
  t0.fillRange(0, t0.length, 0);
  return out;
}

List<int>? _parseArray(String text, String name) {
  final m = RegExp('const $name = <int>\\[([^\\]]*)\\]').firstMatch(text);
  if (m == null) return null;
  final bytes = [for (final h in RegExp(r'0x([0-9a-fA-F]{1,2})').allMatches(m[1]!)) int.parse(h[1]!, radix: 16)];
  return bytes.length == tuningLength ? bytes : null;
}

/// The value back out of a file [tuningSource] wrote, or null.
Uint8List? parseTuningSource(String text) {
  final t = [for (final n in ['_t0', '_t1', '_t2', '_t3']) _parseArray(text, n)];
  final k = RegExp(r'\(i \* (\d+)\) & 31').firstMatch(text);
  if (t.contains(null) || k == null) return null;
  final mul = int.parse(k[1]!);
  final out = Uint8List(tuningLength);
  for (var i = 0; i < tuningLength; i++) {
    if (t[3]![i] >= tuningLength) return null;
    out[i] = t[0]![t[3]![i]] ^ t[1]![i] ^ t[2]![(i * mul) & 31];
  }
  return out;
}

Uint8List? readTuning(String file) {
  try {
    return parseTuningSource(File(file).readAsStringSync());
  } catch (_) {
    return null;
  }
}

String tuningHex(List<int> value) => [for (final b in value) b.toRadixString(16).padLeft(2, '0')].join();

Uint8List? parseTuningHex(String? text) {
  final clean = (text ?? '').replaceAll(RegExp(r'[\s:]'), '');
  if (!RegExp('^[0-9a-fA-F]{${tuningLength * 2}}\$').hasMatch(clean)) return null;
  return Uint8List.fromList([for (var i = 0; i < clean.length; i += 2) int.parse(clean.substring(i, i + 2), radix: 16)]);
}

bool sameTuning(List<int> a, List<int> b) {
  if (a.length != b.length) return false;
  var diff = 0;
  for (var i = 0; i < a.length; i++) {
    diff |= a[i] ^ b[i];
  }
  return diff == 0;
}
